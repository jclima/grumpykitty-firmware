"""Convert a PNG to an LVGL 8 TRUE_COLOR_ALPHA .c file (dino layout).

3 bytes per pixel: RGB565 low byte, RGB565 high byte, alpha (LV_COLOR_16_SWAP 0).
Non-PNG/16-bit/palette input: convert first with `sips -s format png in out.png`.

Usage:  python3 png_to_lvgl_c.py in.png out.c [var_name]
        var_name defaults to ui_img_<basename>_png
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pngio import read_png  # noqa: E402


def encode(rgba):
    out = bytearray()
    for i in range(0, len(rgba), 4):
        r, g, b, a = rgba[i:i + 4]
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        out += bytes((v & 0xFF, v >> 8, a))
    return bytes(out)


def write_c(path, var, w, h, data, src):
    lines = ["    " + ",".join("0x%02X" % v for v in data[k:k + 16]) + "," for k in range(0, len(data), 16)]
    out = "﻿// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 JC Lima\n"
    out += "// Generated by tools/art/png_to_lvgl_c.py from %s\n" % src
    out += "// LVGL version: 8.3.11\n\n#include \"../ui.h\"\n\n"
    out += "#ifndef LV_ATTRIBUTE_MEM_ALIGN\n    #define LV_ATTRIBUTE_MEM_ALIGN\n#endif\n\n"
    out += "// IMAGE DATA: generated\n"
    out += "const LV_ATTRIBUTE_MEM_ALIGN uint8_t %s_data[] = {\n" % var
    out += "\n".join(lines) + "\n};\n"
    out += "const lv_img_dsc_t %s = {\n    .header.always_zero = 0,\n" % var
    out += "    .header.w = %d,\n    .header.h = %d,\n" % (w, h)
    out += "    .data_size = sizeof(%s_data),\n" % var
    out += "    .header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA,\n    .data = %s_data\n};\n\n" % var
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)


def main(argv):
    if len(argv) < 2:
        sys.exit(__doc__)
    src, dst = argv[0], argv[1]
    base = os.path.splitext(os.path.basename(src))[0]
    if base.startswith("ui_img_"):
        base = base[7:]
    if base.endswith("_png"):
        base = base[:-4]
    var = argv[2] if len(argv) > 2 else "ui_img_%s_png" % base
    w, h, rgba = read_png(src)
    write_c(dst, var, w, h, encode(rgba), os.path.basename(src))
    print("wrote %s (%dx%d, %s)" % (dst, w, h, var))


if __name__ == "__main__":
    main(sys.argv[1:])
