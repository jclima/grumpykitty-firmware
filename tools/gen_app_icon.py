#!/usr/bin/env python3
"""Generate 70x70 LVGL TRUE_COLOR_ALPHA app icons (standard library only).

Output layout matches src/ui/images/ui_img_dino_png.c: 3 bytes per pixel =
RGB565 low byte, RGB565 high byte, alpha (LV_COLOR_16_SWAP 0). Glyphs are
dark on a transparent background (the menu button behind is lime). Shapes are
signed distance fields rendered with 4x4 supersampling for anti-aliasing.

Usage:  python3 tools/gen_app_icon.py            # writes all icons
        python3 tools/gen_app_icon.py mic        # one glyph
The generated .c files are committed static sources, not build products.
"""
import math
import os
import sys

SIZE = 70
SS = 4
INK = (0x14, 0x20, 0x00)  # dark olive, reads well on 0xBEE700

# ── distance-field primitives (return < 0 inside) ─────────────────────────


def circle(px, py, cx, cy, r):
    return math.hypot(px - cx, py - cy) - r


def seg(px, py, x1, y1, x2, y2, r):
    """Capsule: segment (x1,y1)-(x2,y2) with radius r."""
    dx, dy = x2 - x1, y2 - y1
    l2 = dx * dx + dy * dy
    t = 0.0 if l2 == 0 else max(0.0, min(1.0, ((px - x1) * dx + (py - y1) * dy) / l2))
    return math.hypot(px - (x1 + t * dx), py - (y1 + t * dy)) - r


def rbox_outline(px, py, x0, y0, x1, y1, rad, th):
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    hx, hy = (x1 - x0) / 2 - rad, (y1 - y0) / 2 - rad
    qx, qy = abs(px - cx) - hx, abs(py - cy) - hy
    d = math.hypot(max(qx, 0), max(qy, 0)) + min(max(qx, qy), 0) - rad
    return abs(d) - th / 2


def arc(px, py, cx, cy, R, th, a0, a1):
    """Ring of radius R, thickness th, limited to angles a0..a1 (deg, y up)."""
    dx, dy = px - cx, cy - py
    r = math.hypot(dx, dy)
    ring = abs(r - R) - th / 2
    a = math.degrees(math.atan2(dy, dx)) % 360
    mid, half = (a0 + a1) / 2, (a1 - a0) / 2
    da = abs((a - mid + 180) % 360 - 180) - half
    return max(ring, da * math.pi / 180 * max(r, 1.0))


def union(*d):
    return min(d)


# ── glyphs ────────────────────────────────────────────────────────────────


def g_mic(x, y):
    return union(
        seg(x, y, 35, 17, 35, 32, 8),
        arc(x, y, 35, 32, 15, 3.2, 180, 360),
        seg(x, y, 35, 47, 35, 54, 1.7),
        seg(x, y, 26, 55, 44, 55, 1.7),
    )


def g_mediaremote(x, y):
    return union(
        circle(x, y, 25, 50, 6.5),
        circle(x, y, 47, 45, 6.5),
        seg(x, y, 30.5, 50, 30.5, 20, 1.8),
        seg(x, y, 52.5, 45, 52.5, 15, 1.8),
        seg(x, y, 30.5, 20, 52.5, 15, 3.2),
    )


def g_slideclicker(x, y):
    return union(
        rbox_outline(x, y, 13, 18, 57, 48, 4, 3.4),
        seg(x, y, 22, 33, 45, 33, 2.0),
        seg(x, y, 45, 33, 37, 26, 2.0),
        seg(x, y, 45, 33, 37, 40, 2.0),
        seg(x, y, 35, 49, 35, 55, 1.7),
        seg(x, y, 27, 56, 43, 56, 1.7),
    )


def g_radarscan(x, y):
    cx, cy = 35, 52
    return union(
        circle(x, y, cx, cy, 3.6),
        arc(x, y, cx, cy, 12, 3.2, 45, 135),
        arc(x, y, cx, cy, 22, 3.2, 45, 135),
        arc(x, y, cx, cy, 32, 3.2, 45, 135),
    )


ICONS = {
    "mic": ("voicerec", g_mic, "Voice Recorder"),
    "media": ("mediaremote", g_mediaremote, "Media Remote"),
    "slide": ("slideclicker", g_slideclicker, "Slide Clicker"),
    "radar": ("radarscan", g_radarscan, "Radar Scan"),
}


def render(fn):
    px = bytearray()
    r, g, b = INK
    rgb565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    lo, hi = rgb565 & 0xFF, rgb565 >> 8
    for j in range(SIZE):
        for i in range(SIZE):
            hits = 0
            for sj in range(SS):
                for si in range(SS):
                    if fn(i + (si + 0.5) / SS, j + (sj + 0.5) / SS) < 0:
                        hits += 1
            a = round(255 * hits / (SS * SS))
            px += bytes((lo, hi, a))
    return bytes(px)


def write_c(path, name, label, data):
    assert len(data) == SIZE * SIZE * 3
    var = "ui_img_%s_png" % name
    lines = []
    for k in range(0, len(data), 16):
        lines.append("    " + ",".join("0x%02X" % v for v in data[k:k + 16]) + ",")
    out = "﻿// Generated by tools/gen_app_icon.py (%s glyph)\n" % label
    out += "// LVGL version: 8.3.11\n\n#include \"../ui.h\"\n\n"
    out += "#ifndef LV_ATTRIBUTE_MEM_ALIGN\n    #define LV_ATTRIBUTE_MEM_ALIGN\n#endif\n\n"
    out += "// IMAGE DATA: generated\n"
    out += "const LV_ATTRIBUTE_MEM_ALIGN uint8_t %s_data[] = {\n" % var
    out += "\n".join(lines) + "\n};\n"
    out += "const lv_img_dsc_t %s = {\n    .header.always_zero = 0,\n" % var
    out += "    .header.w = %d,\n    .header.h = %d,\n" % (SIZE, SIZE)
    out += "    .data_size = sizeof(%s_data),\n" % var
    out += "    .header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA,\n    .data = %s_data\n};\n\n" % var
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)


def main():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "ui", "images")
    keys = sys.argv[1:] or list(ICONS)
    for k in keys:
        name, fn, label = ICONS[k]
        path = os.path.join(root, "ui_img_%s_png.c" % name)
        write_c(path, name, label, render(fn))
        print("wrote", os.path.normpath(path))


if __name__ == "__main__":
    main()
